import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const localTsc = join(root, 'node_modules', 'typescript', 'bin', 'tsc')

/**
 * Run one TypeScript project.
 * @param {string} project - tsconfig path relative to the package root.
 */
function runTsc(project) {
  const args = ['-p', project]
  if (existsSync(localTsc)) execFileSync(process.execPath, [localTsc, ...args], { cwd: root, stdio: 'inherit' })
  else execFileSync(process.platform === 'win32' ? 'tsc.cmd' : 'tsc', args, { cwd: root, stdio: 'inherit' })
}

runTsc('tsconfig.host.json')
runTsc('tsconfig.client.json')

const compiledPath = join(root, '.build', 'client', 'index.js')
let body = readFileSync(compiledPath, 'utf8')

// Inline the vendored QR encoder so the Client bundle stays a single file
// whose only runtime require is "react". The compiled module is flattened into
// the wrapper scope: its two `exports.*` statements are replaced by one local
// binding, which avoids any nested module/exports shadowing.
const qrcodePath = join(root, '.build', 'client', 'qrcode.js')
if (existsSync(qrcodePath)) {
  const qrcodeBody = readFileSync(qrcodePath, 'utf8')
    .replace(/\n$/, '')
    .replace(/^"use strict";\n/, '')
    .replace(/^Object\.defineProperty\(exports, "__esModule", \{ value: true \}\);\n/, '')
    .replace(/^exports\.(\w+) = (\w+);\n/, '')
  if (/(^|[^.\w])exports\b/.test(qrcodeBody)) {
    throw new Error('client qrcode module must not reference `exports` after flattening')
  }
  body = [
    '// --- vendored QR encoder (qrcode-generator 1.4.4, MIT) ---',
    qrcodeBody,
    'const __heluxQrCode = { createQrMatrix };',
    '// --- end vendored QR encoder ---',
    '',
    body.replaceAll('require("./qrcode.js")', '__heluxQrCode'),
  ].join('\n')
}

// The browser module table seeds `react`; every other require would be a missing
// module at materialization time, so a multi-file emit must fail the build.
const externals = [...body.matchAll(/require\("([^"]+)"\)/g)].map((match) => match[1])
const unexpected = [...new Set(externals)].filter((id) => id !== 'react')
if (unexpected.length > 0) {
  throw new Error(`client bundle must be single-file and may require only "react"; found: ${unexpected.join(', ')}`)
}

const indented = body.replace(/\n$/, '').split('\n').map((line) => `\t\t\t${line}`).join('\n')
const wrapped = `// Generated by scripts/build.mjs. Do not edit by hand.\nwindow.__ModuleLoader__.load({\n\tid: ${JSON.stringify(pkg.name)},\n\tfactory(require) {\n\t\tconst module = { exports: {} };\n\t\tconst exports = module.exports;\n\t\t(function (require, module, exports) {\n${indented}\n\t\t})(require, module, exports);\n\t\treturn module.exports;\n\t},\n});\n`

mkdirSync(root, { recursive: true })
writeFileSync(join(root, 'client.js'), wrapped)
console.log(`built client.js (${wrapped.length} bytes) and lib/`)